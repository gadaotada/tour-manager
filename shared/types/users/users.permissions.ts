type ValueOf<T> = T[keyof T];
type PermissionEffect = ValueOf<typeof PERMISSION_EFFECTS>;
type Permission = ValueOf<{
  [Resource in keyof typeof PERMISSIONS]: ValueOf<(typeof PERMISSIONS)[Resource]>;
}>;

type PermissionOverride = {
  permission: Permission;
  effect: PermissionEffect;
};

type UserPermissionOverride = PermissionOverride & {
  user_id: string;
};

