function isPermission(value: string): value is Permission {
  return ALL_PERMISSIONS.includes(value as Permission);
}

function isPermissionEffect(value: string): value is PermissionEffect {
  return Object.values(PERMISSION_EFFECTS).includes(value as PermissionEffect);
}

function resolvePermissions(
  role: Role,
  overrides: readonly PermissionOverride[] = [],
): Permission[] {
  const permissions = new Set<Permission>(ROLE_PERMISSIONS[role]);

  for (const override of overrides) {
    if (override.effect === PERMISSION_EFFECTS.ALLOW) {
      permissions.add(override.permission);
      continue;
    }

    permissions.delete(override.permission);
  }

  return [...permissions];
}

function hasPermission(
  permissions: readonly Permission[] | null | undefined,
  permission: Permission,
): boolean {

  if (!permissions) return false;
  return permissions.includes(permission);
}

